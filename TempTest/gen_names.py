def auto_name(key):
    # split on _ - space
    tokens = re.split(r"[_\- ]+", key)
    parts = []
    for t in tokens:
        if not t:
            continue
        if t in word_map:
            parts.append(word_map[t])
        else:
            # try known compound
            parts.append(word_map.get(t, t))
    # if any part is still latin, label as 未知
    name = "·".join(parts)
    return name

# Build from clips directory
keys = set()
if os.path.isdir(clips_dir):
    for f in os.listdir(clips_dir):
        if f.lower().endswith(".wav"):
            base_name = f[:-4]
            if base_name.endswith("_vibration"):
                base_name = base_name[:-10]
            keys.add(base_name)

lines = []
# sort: keep manual first then auto
sorted_keys = sorted(keys, key=lambda k: (0 if k in overrides else 1, k.lower()))
for k in sorted_keys:
    label = overrides.get(k) or auto_name(k)
    lines.append('\t\t{ "%s", "%s" },' % (k, label))

block = (
    "\tprivate static readonly Dictionary<string, string> clipDisplayNames = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)\n"
    "\t{\n" + "\n".join(lines) + "\n\t};"
)

